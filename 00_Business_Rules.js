// BR-1 — Obligation Category（ADR-P01 已定案清单）
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
//
// Mortgage, Electricity, Water, MaintenanceFee, SinkingFund, QuitRent,
// Assessment, Insurance, Internet, Subscription, PestControl,
// AircondService, WaterFilter, RentalCollection, LeaseRenewal,
// Warranty, DefectLiability
//
// 政策：新增类别只需在 900_PropertyConfig.OBLIGATION_CATEGORIES 加值，
// 不需要 Schema 变更（Category 是字串枚举，非独立表）。★ 2026-08-26
// housekeeping 修正：这句原本写"已被 Migration Test 验证
// （919_Tests_ObligationIntegration.js）"，但该档案已确认是已死、
// 无法执行的旧 Node 沙箱残留（require 路径指向不存在的 tests/shim
// 子目录，详见 00_File_Map.js §5b）——这个政策本身是否仍然成立
// （不需要 Schema 变更）没有改变，只是不能再引用那个已经跑不动的
// 档案当作验证依据；如需要重新验证，走 900_PropertyConfig.js 本身
// 的 DEFECT_CATEGORIES 就是同一种"字串枚举、改值不改 Schema"模式，
// 本次 ADR-P19 才刚实际验证过。
//
// 政策：每个类别不预设不同的付款规则/逾期规则——所有类别共用同一套
// BR-2~BR-5，除非未来有具体需求要求某类别特殊处理（例如 Mortgage
// 可能需要跟 Loan 的 Outstanding Balance 联动，那是 915 的范围，不是
// Obligation Engine 本身要处理的差异）。


// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// BR-2 — Payment Rules 付款规则
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
//
// - 每笔 Occurrence 只能被标记 Paid 一次；重复缴费指令是幂等 no-op，
//   不是错误（呼应真实世界"我付过了，你又叫我付一次"这种情境不该
//   被当成使用者的错）。
// - PaidAmount ≠ Amount 时允许（部分缴费 / 超额缴费），标记但不阻挡——
//   业务判断是：宁可先记录下来让人后续核对，也不要因为金额对不上
//   就整笔拒绝，那样反而丢失了"到底缴了多少"这个事实。
// - 修正已缴记录（金额打错等）一律走 ReversePayment + 重新
//   RecordPayment，不直接改动原记录（P10/ADR-P06 的具体政策落实，
//   不是本文件重新定义）。


// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// BR-3 — Recurring Rule 重复规则
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
//
// 支援 Frequency：Weekly / Monthly / Quarterly / HalfYearly / Yearly /
// Custom（固定天数间隔）。
//
// 政策：月/季/年一律用日历月份加减，月底自动 clamp 到目标月份的
// 实际最后一天（1/31 + 1 月 = 2/28 或 2/29，绝不溢出到 3 月）——这是
// 业务政策，不是技术细节：房贷/管理费这类每月费用，使用者期望的是
// "下个月的对应日"，日历语意錯了会让人对帐对不起来。
//
// 政策：Custom 目前只支援固定天数间隔，不支援 Cron 式表达式——够用
// 就好，不预先支援没人要求的弹性（Speculative Design）。


// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// BR-4 — Overdue Rule & Grace Period 逾期规则与宽限期
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
//
// 政策：到期日 + GraceDays（默认 0，可逐笔 Obligation 覆写）内缴费
// 不算逾期。
//
// 政策：Overdue 永远是当下查询时依（今天 > 到期日+宽限期）即时算出，
// 不写入、不排程判定（技术实作见 ADR-P02 Addendum；这里记的是"为什么
// 需要这条政策"：如果写入一个 Overdue 状态栏位，就需要某种排程去
// 更新它，而 Property OS 的架构原则不允许自建 Trigger，所以业务政策
// 跟架构限制在这里是彼此呼应、不是互相妥协）。


// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// BR-5 — Reminder Policy 提醒政策
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
//
// 默认 Offset：到期前 30/14/7/3/1 天、当天、逾期后 1/3/7 天。
// 可在个别 Obligation 层级覆写（例如 Insurance 续保可能想要更早提醒）。
//
// 政策：AutoGenerate=false 的 Obligation，缴费后不自动产生下一期——
// 用于需要人工确认才续期的义务（业务判断：不是所有循环费用都应该
// 无条件自动续下去，例如尚在考虑是否续约的订阅）。


// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// BR-6 — Rule 终止政策：Cancelled vs Completed
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
//
// 政策：区分"使用者主动取消"（Cancelled）与"自然到期"（Completed，
// 由 EndDate 触发）——这不只是技术上的两个 enum 值，是业务上真的
// 不同的两件事：一笔贷款正常还完（Completed）跟使用者提前卖房不再
// 需要追踪这笔房贷（Cancelled）在未来的报表/税务情境下，语意不同，
// 值得区分而不是都归成同一种"结束"。
//
